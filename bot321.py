def find_cabinet(rows, r_idx, c_idx):
    """
    Ищет кабинет в текущей строке или строке ниже в колонке справа.
    """
    # 1. Проверяем текущую строку, ячейку сразу справа
    if r_idx < len(rows) and len(rows[r_idx]) > c_idx + 1:
        cab = rows[r_idx][c_idx + 1].strip()
        if cab and cab not in ["-", "."]: return cab
        
    # 2. Проверяем строку ниже (где фамилия учителя), ячейку сразу справа
    if r_idx + 1 < len(rows) and len(rows[r_idx + 1]) > c_idx + 1:
        cab = rows[r_idx + 1][c_idx + 1].strip()
        if cab and cab not in ["-", "."]: return cab
        
    return ""

